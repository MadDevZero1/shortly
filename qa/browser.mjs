import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { randomBytes } from 'node:crypto';

const base = process.env.FRONTEND_URL || 'http://localhost:5173';
const output = new URL('../docs/screenshots/',import.meta.url);
await mkdir(output,{recursive:true});
const browser = await chromium.launch(process.env.BROWSER_CHANNEL ? {channel:process.env.BROWSER_CHANNEL} : {channel:'chrome'});
let currentPage;
try {
  const context = await browser.newContext({viewport:{width:1440,height:1000},reducedMotion:'reduce'});
  const page = await context.newPage();
  currentPage=page;
  const failures=[];
  page.on('pageerror',error=>failures.push(error.message));
  await page.goto(base);
  await page.getByRole('heading',{name:/Good things deserve/}).waitFor();
  await page.screenshot({path:new URL('landing-desktop.png',output).pathname.replace(/^\/([A-Za-z]:)/,'$1'),fullPage:true});
  for (const width of [375,768,1024,1440]) {
    await page.setViewportSize({width,height:900});
    await page.screenshot({path:new URL(`landing-${width}.png`,output).pathname.replace(/^\/([A-Za-z]:)/,'$1'),fullPage:true});
    const overflow=await page.evaluate(()=>[...document.querySelectorAll('body *')].filter(el=>el.getBoundingClientRect().right>innerWidth+1).map(el=>({tag:el.tagName,cls:el.className,right:el.getBoundingClientRect().right})).slice(0,10));
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),`No overflow at ${width}: ${JSON.stringify(overflow)}`);
  }
  await page.setViewportSize({width:375,height:900});
  await page.screenshot({path:new URL('landing-mobile.png',output).pathname.replace(/^\/([A-Za-z]:)/,'$1'),fullPage:true});
  await page.goto(`${base}/dashboard`);
  await page.waitForURL(/\/auth/);
  console.log('PASS: landing desktop/mobile, 375/768/1024/1440 widths, protected route redirects to sign-in.');
  await page.setViewportSize({width:1440,height:1000});
  await page.getByRole('button',{name:'New here? Create an account'}).click();
  const email=`shortly-qa-${Date.now()}@example.com`,password=`A1!${randomBytes(18).toString('hex')}`;
  await page.getByLabel('Your name').fill('Browser verification');
  await page.getByLabel('Email address').fill(email);
  await page.getByLabel('Password',{exact:true}).fill(password);
  await page.getByLabel('Confirm password').fill(password+'wrong');
  await page.getByRole('button',{name:'Create account',exact:true}).click();
  await page.getByText('Passwords do not match.').waitFor();
  await page.getByLabel('Confirm password').fill(password);
  await page.getByRole('button',{name:'Show password'}).click();
  assert.equal(await page.getByLabel('Password',{exact:true}).getAttribute('type'),'text');
  await page.getByRole('button',{name:'Hide password'}).click();
  await page.getByRole('button',{name:'Create account',exact:true}).click();
  await page.waitForURL(/\/dashboard/,{timeout:45000});
  await page.getByRole('heading',{name:'Your links.',exact:true}).waitFor();
  await page.getByLabel('Your long link').fill('https://example.com/browser-verification');
  await page.getByRole('button',{name:'Shorten link',exact:true}).click();
  await page.waitForURL(/\/result\//,{timeout:30000});
  const shortUrl=await page.getByLabel('Your short URL').inputValue();
  const response=await context.request.get(shortUrl,{maxRedirects:0});
  assert.equal(response.status(),302);
  assert.equal(response.headers().location,'https://example.com/browser-verification');
  await page.getByRole('link',{name:'View analytics'}).click();
  await page.getByRole('heading',{name:'Link insights.'}).waitFor();
  await page.getByText('example.com/browser-verification',{exact:false}).first().waitFor();
  await page.screenshot({path:new URL('analytics-desktop.png',output).pathname.replace(/^\/([A-Za-z]:)/,'$1'),fullPage:true});
  await page.setViewportSize({width:375,height:900});
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),'Analytics mobile has no overflow');
  await page.screenshot({path:new URL('analytics-mobile.png',output).pathname.replace(/^\/([A-Za-z]:)/,'$1'),fullPage:true});
  await page.setViewportSize({width:1440,height:1000});
  await page.goto(`${base}/dashboard`);
  await page.getByRole('heading',{name:'Your links.',exact:true}).waitFor();
  await page.locator('.link-row').first().waitFor();
  await page.screenshot({path:new URL('dashboard-desktop.png',output).pathname.replace(/^\/([A-Za-z]:)/,'$1'),fullPage:true});
  await page.setViewportSize({width:375,height:900});
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),'Dashboard mobile has no overflow');
  await page.screenshot({path:new URL('dashboard-mobile.png',output).pathname.replace(/^\/([A-Za-z]:)/,'$1'),fullPage:true});
  await page.getByRole('textbox',{name:'Search your links'}).fill('this-search-has-no-match');
  await page.getByRole('button',{name:'Search',exact:true}).click();
  await page.getByText('No links match your search.').waitFor();
  await page.getByRole('button',{name:'Sign out',exact:true}).click();
  await page.waitForURL(base+'/');
  await page.goto(`${base}/dashboard`);
  await page.waitForURL(/\/auth/);
  await page.getByLabel('Email address').fill(email);
  await page.getByLabel('Password',{exact:true}).fill(password);
  await page.getByRole('button',{name:'Sign in',exact:true}).click();
  await page.waitForURL(/\/dashboard/);
  await page.locator('.link-row').first().waitFor();
  page.once('dialog',dialog=>dialog.accept());
  await page.getByRole('button',{name:/Delete link/}).first().click();
  await page.getByText('Your first link starts here.').waitFor();
  assert.equal((await context.request.get(shortUrl,{maxRedirects:0})).status(),404);
  await page.getByRole('button',{name:'Sign out',exact:true}).click();
  await page.waitForURL(base+'/');
  assert.deepEqual(failures,[]);
  console.log('PASS: password checks, managed sign-up, session, create, result, public redirect, private analytics, deletion, reload, sign-out and protected route; no page exceptions.');
  console.log(`Screenshots saved under docs/screenshots. Synthetic account retained on ${base.includes('localhost') ? 'development' : 'production'} Auth branch; test link deleted.`);
} catch(error) {
  if(currentPage){await currentPage.screenshot({path:new URL('browser-failure.png',output).pathname.replace(/^\/([A-Za-z]:)/,'$1'),fullPage:true});console.error('Visible errors:',await currentPage.getByRole('alert').allTextContents());}
  throw error;
} finally { await browser.close(); }
